def stage_help_tooltip(stage: str) -> str:
    rows = []
    for heading, entries in HELP_SECTIONS[stage]:
        rows.append(f'<tr><td colspan="2"><b>{escape(heading)}</b></td></tr>')
        for color, text in entries:
            description = escape(text).replace("\n", "<br>")
            if color:
                swatch = f'<font color="{color}">━</font>'
                rows.append(f'<tr><td width="24" valign="top">{swatch}</td><td>{description}</td></tr>')
            else:
                rows.append(f'<tr><td colspan="2">{description}</td></tr>')
    return '<qt><table width="340" cellspacing="4">' + ''.join(rows) + '</table></qt>'
